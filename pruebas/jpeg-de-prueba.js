// Un JPEG mínimo para las pruebas del PDF: SOI, APP0, la marca SOF (0xC0, o 0xC2 la progresiva)
// con su medida, unos bytes y EOI. No se puede dibujar, pero el PDF solo lee su SOF y lo copia
// tal cual, que es lo que se prueba. `relleno` cambia los bytes: dos fotos, dos huellas.
export function jpegDePrueba(ancho, alto, { sof = 0xc0, relleno = 7, semilla = 37 } = {}) {
  return Uint8Array.from([
    0xff, 0xd8,
    0xff, 0xe0, 0x00, 0x10, 0x4a, 0x46, 0x49, 0x46, 0x00, 0x01, 0x01, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00,
    0xff, sof, 0x00, 0x11, 0x08, alto >> 8, alto & 255, ancho >> 8, ancho & 255, 0x03, 0x01, 0x22, 0x00, 0x02, 0x11, 0x01, 0x03, 0x11, 0x01,
    ...Array.from({ length: relleno }, (_, i) => (i * semilla) & 0x7f),
    0xff, 0xd9,
  ]);
}
